        private async Task SafeEditMessageTextAsync(ITelegramBotClient botClient, long chatId, int messageId, string text, InlineKeyboardMarkup replyMarkup, CancellationToken cancellationToken)
        {
            try
            {
                await botClient.EditMessageTextAsync(chatId, messageId, text: text, replyMarkup: replyMarkup, cancellationToken: cancellationToken);
            }
            catch (Telegram.Bot.Exceptions.ApiRequestException ex)
            {
                if (ex.Message != null && ex.Message.Contains("message is not modified", StringComparison.OrdinalIgnoreCase))
                    return;

                _logger.LogError(ex, "SafeEditMessageTextAsync failed. ChatId={ChatId} MessageId={MessageId} TextLength={TextLength} ErrorCode={ErrorCode} Error={Error}",
                    chatId, messageId, text?.Length ?? 0, ex.ErrorCode, ex.Message);
                try
                {
                    var safeText = text ?? string.Empty;
                    await botClient.SendTextMessageAsync(chatId, safeText, replyMarkup: replyMarkup, cancellationToken: cancellationToken);
                }
                catch (Telegram.Bot.Exceptions.ApiRequestException sendEx)
                {
                    _logger.LogError(sendEx, "SafeEditMessageTextAsync fallback send failed. ChatId={ChatId} ErrorCode={ErrorCode} Error={Error}",
                        chatId, sendEx.ErrorCode, sendEx.Message);
                }
            }
        }
