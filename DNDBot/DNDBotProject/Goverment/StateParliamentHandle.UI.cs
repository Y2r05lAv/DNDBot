        public async Task EditMessageInfoForParlament(ITelegramBotClient botClient, long chatId, int msgId, long userId, CancellationToken cancellationToken)
        {
            if (!TryGetCountryForDeputy(userId, out int countryId, out string error))
            {
                await SafeEditMessageTextAsync(
                    botClient,
                    chatId,
                    msgId,
                    error,
                    StateKeyboardBuilder.ParliamentStateKeyboard(),
                    cancellationToken
                );
                return;
            }

            ParliamentProvisioningService.ParliamentProvisioningResult provisionResult;
            try
            {
                provisionResult = ParliamentProvisioningService.EnsureParliamentForCountry(countryId);
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Parliament provisioning failed. UserId={UserId} CountryId={CountryId}", userId, countryId);
                await SafeEditMessageTextAsync(
                    botClient,
                    chatId,
                    msgId,
                    "🏛 Функції парламенту\nНе вдалося підготувати парламент. Спробуйте ще раз пізніше.",
                    StateKeyboardBuilder.ParliamentLockedKeyboard(),
                    cancellationToken
                );
                return;
            }

            if (!provisionResult.HasParliament)
            {
                var country = CountriesData.GetCountryById(countryId);
                string hint = country == null
                    ? "Парламент поки недоступний."
                    : $"{ParliamentProvisioningService.BuildEligibilityHint(country)}\nПоточні значення: стабільність {country.Stability:0.##}% | казна {TreasuryCoinService.FormatTreasury(country.Treasury, country.CountryId)}";

                string lockedText =
                    $"🏛 Функції парламенту\n" +
                    $"Парламент поки недоступний.\n" +
                    $"{provisionResult.EligibilityReason}\n" +
                    $"{hint}";

                await SafeEditMessageTextAsync(
                    botClient,
                    chatId,
                    msgId,
                    lockedText,
                    StateKeyboardBuilder.ParliamentLockedKeyboard(),
                    cancellationToken
                );
                return;
            }

            bool isActive = ActiveParliamentSessionByCountry.ContainsKey(countryId);
            bool isPending = PendingSessionCountryByUser.Values.Contains(countryId);
            int activeDeputies = DeputiesData.GetByCountry(countryId, aliveOnly: true).Count;
            int partiesCount = PartiesData.GetAllParties().Count(p => p.CountryId == countryId);
            bool autoStructureEnabled = ParliamentProvisioningService.IsAutoStructureEnabled(countryId);

            string status = isActive
                ? "✅ Сесія активна"
                : isPending
                    ? "🕓 Сесія скликається"
                    : "⚪ Сесія не скликана";

            string text = $"🏛 Функції парламенту\n{status}";

            if (provisionResult.AutoUnlocked)
                text += "\n🆕 Парламент відкрито автоматично для цієї країни.";

            if (provisionResult.AutoGeneratedStructure)
                text += $"\nСформовано: фракцій +{provisionResult.PartiesCreated}, депутатів +{provisionResult.DeputiesCreated}.";

            if (provisionResult.TargetSeats > 0)
                text += $"\nЛіміт мандатів / ціль фракцій: {provisionResult.TargetSeats} / {provisionResult.TargetFractions}";
            text += $"\nФактично депутати / партії: {activeDeputies} / {partiesCount}";
            text += $"\nАвтодозаповнення: {(autoStructureEnabled ? "увімкнено" : "вимкнено")}";

            await SafeEditMessageTextAsync(
                botClient,
                chatId,
                msgId,
                text,
                StateKeyboardBuilder.ParliamentStateKeyboard(),
                cancellationToken
            );
        }

        private async Task EditMessageInfoForStateMain(ITelegramBotClient botClient, long chatId, int msgId, long userId, CancellationToken cancellationToken)
        {
            var provider = new StateDataProvider();
            var selectedCountryId = StateAdministration.GetSelectedCountryIdForUser(userId);
            var stateData = provider.GetStateData(userId, selectedCountryId);

            bool isCountryOwner = false;
            if (selectedCountryId.HasValue)
            {
                var assigned = UserData.GetActiveCharacterCountryId(userId);
                isCountryOwner = assigned.HasValue && assigned.Value == selectedCountryId.Value;
            }

            var text = StateMessageBuilder.BuildMainStateMessage(stateData);
            var keyboard = StateKeyboardBuilder.MainStateKeyboard(
                userId,
                stateData?.CountryName,
                stateData?.HasParliament,
                userId == masterID,
                isCountryOwner
            );

            await SafeEditMessageTextAsync(
                botClient,
                chatId,
                msgId,
                text,
                keyboard,
                cancellationToken
            );
        }

