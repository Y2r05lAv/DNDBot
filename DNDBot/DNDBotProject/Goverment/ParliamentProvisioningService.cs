using DNDBot.BotSystem;
using DNDBot.DataBase;
using System;
using System.Collections.Generic;
using System.Linq;

namespace DNDBot.Goverment
{
    internal static class ParliamentProvisioningService
    {
        private const float StableStabilityThreshold = 66f;
        private const float StableUnrestThreshold = 40f;
        private const float StableCorruptionThreshold = 55f;
        private const long WealthFloorTreasury = 600_000L;
        private const decimal WealthPerCitizenMultiplier = 30m;
        private const string AutoStructureConfigKey = "ParliamentAutoStructureEnabled";
        private static readonly object AutoStructureSync = new();
        private static readonly Dictionary<int, bool> AutoStructureOverrideByCountry = new();

        internal sealed class ParliamentProvisioningResult
        {
            public bool HasParliament { get; set; }
            public bool AutoUnlocked { get; set; }
            public bool AutoGeneratedStructure { get; set; }
            public int TargetSeats { get; set; }
            public int TargetFractions { get; set; }
            public int PartiesCreated { get; set; }
            public int DeputiesCreated { get; set; }
            public string EligibilityReason { get; set; } = string.Empty;
        }

        private sealed class PartySeed
        {
            public string Name { get; set; } = string.Empty;
            public string Ideology { get; set; } = string.Empty;
            public bool GovernmentAligned { get; set; }
            public int Influence { get; set; }
            public int Discipline { get; set; }
        }

        private static readonly (string Name, string Ideology)[] GovernmentPartyPool =
        {
            ("Коаліція розвитку", "Центристи"),
            ("Партія стабільності", "Державники"),
            ("Блок модернізації", "Ліберали"),
            ("Союз реформ", "Прагматики"),
            ("Партія національного курсу", "Консерватори")
        };

        private static readonly (string Name, string Ideology)[] OppositionPartyPool =
        {
            ("Громадянська платформа", "Ліберали"),
            ("Ліга справедливості", "Соціал-демократи"),
            ("Народний союз", "Народники"),
            ("Вільна опозиція", "Реформісти"),
            ("Альянс регіонів", "Децентралісти"),
            ("Партія громад", "Комунітарії")
        };

        public static ParliamentProvisioningResult EnsureParliamentForCountry(int countryId)
        {
            var result = new ParliamentProvisioningResult();
            if (countryId <= 0)
                return result;

            var country = CountriesData.GetCountryById(countryId);
            if (country == null)
                return result;

            bool eligible = IsEligibleForAutoUnlock(country, out string reason);
            result.EligibilityReason = reason;

            bool countryChanged = false;
            if (!country.HasParliament)
            {
                if (!eligible)
                    return result;

                country.HasParliament = true;
                result.AutoUnlocked = true;
                countryChanged = true;
            }

            if (EnsureCountryParliamentDefaults(country))
                countryChanged = true;

            if (countryChanged)
            {
                country.LastUpdate = DateTime.UtcNow;
                CountriesData.UpdateCountry(country);
            }

            result.HasParliament = country.HasParliament;
            result.TargetSeats = Math.Max(1, country.ParliamentSeats);
            result.TargetFractions = Math.Max(1, country.ParliamentFractions);

            EnsureParliamentRecord(country);
            bool autoStructureEnabled = IsAutoStructureEnabled(country.CountryId);

            var parties = PartiesData.GetAllParties()
                .Where(p => p.CountryId == country.CountryId)
                .OrderBy(p => p.PartyId)
                .ToList();

            if (parties.Count == 0 && autoStructureEnabled)
            {
                result.PartiesCreated = CreateDefaultParties(country);
                parties = PartiesData.GetAllParties()
                    .Where(p => p.CountryId == country.CountryId)
                    .OrderBy(p => p.PartyId)
                    .ToList();
            }

            int seatsTarget = Math.Max(1, country.ParliamentSeats);
            var aliveDeputies = DeputiesData.GetByCountry(country.CountryId, aliveOnly: true);
            if (autoStructureEnabled && aliveDeputies.Count < seatsTarget && parties.Count > 0)
            {
                int needed = seatsTarget - aliveDeputies.Count;
                result.DeputiesCreated = CreateDefaultDeputies(country, parties, needed);
            }

            result.AutoGeneratedStructure = result.PartiesCreated > 0 || result.DeputiesCreated > 0;
            return result;
        }

        public static bool IsAutoStructureEnabled(int countryId)
        {
            if (countryId <= 0)
                return true;

            lock (AutoStructureSync)
            {
                if (AutoStructureOverrideByCountry.TryGetValue(countryId, out bool overrideValue))
                    return overrideValue;
            }

            return EconomyConfigData.GetDecimalForCountry(countryId, AutoStructureConfigKey, 1m) >= 0.5m;
        }

        public static void SetAutoStructureEnabled(int countryId, bool enabled)
        {
            if (countryId <= 0)
                return;

            lock (AutoStructureSync)
            {
                AutoStructureOverrideByCountry[countryId] = enabled;
            }

            EconomyConfigData.UpsertCountryDecimal(countryId, AutoStructureConfigKey, enabled ? 1m : 0m);
        }

        public static string BuildEligibilityHint(CountryRecord country)
        {
            long requiredTreasury = ComputeWealthThreshold(country?.Population ?? 0L);
            return $"Умови доступу: стабільність від {StableStabilityThreshold:0}% або казна від {requiredTreasury:N0}.";
        }

        internal static bool IsCountryWealthy(CountryRecord country)
        {
            if (country == null || country.IsCollapsed)
                return false;

            long treasury = Math.Max(0L, country.Treasury);
            long threshold = ComputeWealthThreshold(Math.Max(0L, country.Population));
            return treasury >= threshold;
        }

        private static bool IsEligibleForAutoUnlock(CountryRecord country, out string reason)
        {
            float stability = Math.Max(0f, country.Stability);
            float unrest = Math.Max(0f, country.Unrest);
            float corruption = Math.Max(0f, country.Corruption);
            long treasury = Math.Max(0L, country.Treasury);
            long population = Math.Max(0L, country.Population);

            bool stable = stability >= StableStabilityThreshold &&
                          unrest <= StableUnrestThreshold &&
                          corruption <= StableCorruptionThreshold &&
                          !country.IsCollapsed;

            long wealthThreshold = ComputeWealthThreshold(population);
            bool wealthy = treasury >= wealthThreshold && !country.IsCollapsed;

            if (stable && wealthy)
            {
                reason = "Країна стабільна і заможна.";
                return true;
            }

            if (stable)
            {
                reason = "Країна стабільна.";
                return true;
            }

            if (wealthy)
            {
                reason = "Країна заможна.";
                return true;
            }

            reason = BuildEligibilityHint(country);
            return false;
        }

        private static long ComputeWealthThreshold(long population)
        {
            population = Math.Max(1L, population);
            decimal scaled = population * WealthPerCitizenMultiplier;
            long byPopulation = (long)Math.Round(scaled, MidpointRounding.AwayFromZero);
            return Math.Max(WealthFloorTreasury, byPopulation);
        }

        private static bool EnsureCountryParliamentDefaults(CountryRecord country)
        {
            bool changed = false;

            int seats = ComputeDefaultSeats(country);
            if (country.ParliamentSeats <= 0)
            {
                country.ParliamentSeats = seats;
                changed = true;
            }

            int fractions = ComputeDefaultFractions(country, Math.Max(1, country.ParliamentSeats));
            if (country.ParliamentFractions <= 0)
            {
                country.ParliamentFractions = fractions;
                changed = true;
            }

            if (country.ParliamentSupport <= 0f || country.ParliamentSupport > 100f)
            {
                country.ParliamentSupport = ComputeGovernmentSupport(country);
                changed = true;
            }

            if (country.OppositionStrength <= 0f || country.OppositionStrength > 100f)
            {
                country.OppositionStrength = Math.Clamp(100f - country.ParliamentSupport, 10f, 90f);
                changed = true;
            }

            if (country.MaxLawsAllowed <= 0)
            {
                country.MaxLawsAllowed = Math.Clamp(country.ParliamentSeats / 6, 8, 40);
                changed = true;
            }

            return changed;
        }

        private static int ComputeDefaultSeats(CountryRecord country)
        {
            long population = Math.Max(1L, country.Population);
            int populationSeats = (int)Math.Round(population / 12_000d, MidpointRounding.AwayFromZero);
            int governanceBonus = Math.Max(0, country.GovernmentLevel) * 2;
            int seats = 40 + populationSeats + governanceBonus;
            return Math.Clamp(seats, 45, 260);
        }

        private static int ComputeDefaultFractions(CountryRecord country, int seats)
        {
            int bySeats = (int)Math.Round(seats / 28d, MidpointRounding.AwayFromZero);
            if (country.Stability >= 80f)
                bySeats += 1;
            return Math.Clamp(bySeats, 3, 8);
        }

        private static float ComputeGovernmentSupport(CountryRecord country)
        {
            float support =
                country.PopularLoyalty * 0.45f +
                country.EliteLoyalty * 0.2f +
                country.Stability * 0.35f -
                country.Corruption * 0.2f;
            return Math.Clamp(support, 25f, 85f);
        }

        private static void EnsureParliamentRecord(CountryRecord country)
        {
            var existing = ParliamentData.GetAllParliaments()
                .FirstOrDefault(p => p.CountryId == country.CountryId);

            decimal support = decimal.Round(Math.Clamp((decimal)country.ParliamentSupport, 0m, 100m), 2, MidpointRounding.AwayFromZero);
            int seats = Math.Max(1, country.ParliamentSeats);

            if (existing == null)
            {
                ParliamentData.AddParliament(new ParliamentRecord
                {
                    CountryId = country.CountryId,
                    TotalSeats = seats,
                    QuorumPercent = 60m,
                    GovernmentSupport = support,
                    IsSessionActive = false,
                    LastSessionStart = null
                });
                return;
            }

            bool changed = false;
            if (existing.TotalSeats != seats)
            {
                existing.TotalSeats = seats;
                changed = true;
            }
            if (existing.GovernmentSupport != support)
            {
                existing.GovernmentSupport = support;
                changed = true;
            }
            if (existing.QuorumPercent <= 0m || existing.QuorumPercent > 100m)
            {
                existing.QuorumPercent = 60m;
                changed = true;
            }

            if (changed)
                ParliamentData.UpdateParliament(existing);
        }

        private static int CreateDefaultParties(CountryRecord country)
        {
            int targetFractions = Math.Max(1, country.ParliamentFractions);
            int supportShare = Math.Clamp((int)Math.Round(country.ParliamentSupport, MidpointRounding.AwayFromZero), 30, 80);
            int oppositionShare = Math.Clamp(100 - supportShare, 20, 70);

            int governmentParties = targetFractions == 1
                ? 1
                : Math.Clamp((int)Math.Round(targetFractions * 0.4, MidpointRounding.AwayFromZero), 1, targetFractions - 1);
            int oppositionParties = Math.Max(0, targetFractions - governmentParties);

            var rng = CreateRng(country.CountryId, salt: 1007);
            var govWeights = SplitWeight(supportShare, governmentParties, rng);
            var oppWeights = oppositionParties > 0
                ? SplitWeight(oppositionShare, oppositionParties, rng)
                : new List<int>();

            var seeds = new List<PartySeed>();
            for (int i = 0; i < governmentParties; i++)
            {
                var pool = GovernmentPartyPool[i % GovernmentPartyPool.Length];
                seeds.Add(new PartySeed
                {
                    Name = BuildPartyName(pool.Name, i, governmentParties),
                    Ideology = pool.Ideology,
                    GovernmentAligned = true,
                    Influence = govWeights[i],
                    Discipline = Math.Clamp((int)Math.Round(country.Stability + rng.Next(-10, 13), MidpointRounding.AwayFromZero), 35, 95)
                });
            }

            for (int i = 0; i < oppositionParties; i++)
            {
                var pool = OppositionPartyPool[i % OppositionPartyPool.Length];
                seeds.Add(new PartySeed
                {
                    Name = BuildPartyName(pool.Name, i, oppositionParties),
                    Ideology = pool.Ideology,
                    GovernmentAligned = false,
                    Influence = oppWeights[i],
                    Discipline = Math.Clamp((int)Math.Round(country.Stability + rng.Next(-18, 9), MidpointRounding.AwayFromZero), 25, 90)
                });
            }

            int created = 0;
            foreach (var seed in seeds.OrderByDescending(s => s.Influence))
            {
                PartiesData.AddParty(new PartyRecord
                {
                    CountryId = country.CountryId,
                    Name = seed.Name,
                    Ideology = seed.Ideology,
                    Discipline = seed.Discipline,
                    GovernmentAligned = seed.GovernmentAligned,
                    Influence = Math.Clamp(seed.Influence, 1, 100)
                });
                created++;
            }

            return created;
        }

        private static int CreateDefaultDeputies(CountryRecord country, List<PartyRecord> parties, int neededCount)
        {
            if (neededCount <= 0 || parties == null || parties.Count == 0)
                return 0;

            var existingNames = DeputiesData.GetAllDeputies()
                .Where(d => d.CountryId == country.CountryId)
                .Select(d => d.Name ?? string.Empty)
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            var rng = CreateRng(country.CountryId, salt: 2003);
            int created = 0;

            for (int i = 0; i < neededCount; i++)
            {
                var party = PickPartyByInfluence(parties, rng);
                if (party == null)
                    break;

                string name = GenerateUniqueDeputyName(rng, existingNames);
                int corruption = Math.Clamp((int)Math.Round(country.Corruption + rng.Next(-18, 19), MidpointRounding.AwayFromZero), 0, 100);
                int loyaltyBaseline = party.GovernmentAligned ? 58 : 42;
                int loyalty = Math.Clamp((int)Math.Round(loyaltyBaseline + (country.Stability - 50f) * 0.35f + rng.Next(-14, 15), MidpointRounding.AwayFromZero), 5, 95);
                int influence = Math.Clamp(party.Influence + rng.Next(-20, 21), 10, 100);
                int attendance = Math.Clamp((int)Math.Round(55 + country.Stability * 0.35f + party.Discipline * 0.2f - corruption * 0.15f + rng.Next(-12, 13), MidpointRounding.AwayFromZero), 35, 98);

                var deputy = new DeputyRecord
                {
                    CountryId = country.CountryId,
                    PartyId = party.PartyId,
                    Name = name,
                    Loyalty = loyalty,
                    Corruption = corruption,
                    Influence = influence,
                    AttendanceChance = attendance,
                    IsAlive = true
                };

                int? newId = DeputiesData.AddDeputyAndReturnId(deputy);
                if (!newId.HasValue)
                    continue;

                PartyMembersData.AddPartyMember(new PartyMemberRecord
                {
                    PartyId = party.PartyId,
                    DeputyId = newId.Value
                });

                created++;
            }

            return created;
        }

        private static PartyRecord PickPartyByInfluence(List<PartyRecord> parties, Random rng)
        {
            if (parties == null || parties.Count == 0)
                return null;

            int totalWeight = parties.Sum(p => Math.Max(1, p.Influence));
            if (totalWeight <= 0)
                return parties[rng.Next(0, parties.Count)];

            int roll = rng.Next(1, totalWeight + 1);
            int running = 0;
            foreach (var party in parties)
            {
                running += Math.Max(1, party.Influence);
                if (roll <= running)
                    return party;
            }

            return parties[^1];
        }

        private static string GenerateUniqueDeputyName(Random rng, HashSet<string> existingNames)
        {
            for (int attempt = 0; attempt < 10; attempt++)
            {
                NameStyle style = (NameStyle)rng.Next(0, 4);
                Gender gender = (Gender)rng.Next(0, 2);
                string generated = FantasyNameGenerator.GenerateFullName(style, gender);
                if (existingNames.Add(generated))
                    return generated;
            }

            string fallback = $"Депутат {existingNames.Count + 1}";
            existingNames.Add(fallback);
            return fallback;
        }

        private static string BuildPartyName(string baseName, int index, int totalInGroup)
        {
            if (index <= 0 || totalInGroup <= 1)
                return baseName;
            return $"{baseName} {index + 1}";
        }

        private static List<int> SplitWeight(int total, int count, Random rng)
        {
            count = Math.Max(1, count);
            total = Math.Max(count, total);

            int minEach = Math.Max(1, Math.Min(8, total / count / 2));
            var parts = Enumerable.Repeat(minEach, count).ToList();

            int remaining = total - (minEach * count);
            for (int i = 0; i < remaining; i++)
            {
                int idx = rng.Next(0, count);
                parts[idx]++;
            }

            return parts;
        }

        private static Random CreateRng(int countryId, int salt)
        {
            int seed = countryId * 48611;
            seed ^= salt * 73856093;
            return new Random(seed);
        }
    }
